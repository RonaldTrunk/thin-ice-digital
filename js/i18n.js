  function currentLang() {
    const params = new URLSearchParams(window.location.search);
    const fromUrl = (params.get("lang") || "").toLowerCase();
    if (T[fromUrl]) return fromUrl;
    try {
      const stored = localStorage.getItem(STORAGE);
      if (T[stored]) return stored;
    } catch (e) { /* ignore */ }
    const nav = (navigator.language || "en").slice(0, 2).toLowerCase();
    if (T[nav]) return nav;
    return "en";
  }

  function apply(lang) {
    const pack = T[lang] || T.en;
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      const key = el.getAttribute("data-i18n");
      if (pack[key] != null) el.textContent = pack[key];
    });
    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      const key = el.getAttribute("data-i18n-html");
      if (pack[key] != null) el.innerHTML = pack[key];
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      const key = el.getAttribute("data-i18n-aria");
      if (pack[key] != null) el.setAttribute("aria-label", pack[key]);
    });
    const page = document.documentElement.getAttribute("data-page") || "home";
    const titles = { home: "meta.title", impressum: "imp.meta", privacy: "priv.meta", error: "err.meta" };
    const titleKey = titles[page];
    if (titleKey && pack[titleKey]) document.title = pack[titleKey];
    const desc = document.querySelector('meta[name="description"]');
    if (desc && pack["meta.desc"] && page === "home") desc.setAttribute("content", pack["meta.desc"]);
    document.querySelectorAll(".lang-switch [data-lang]").forEach(function (btn) {
      btn.setAttribute("aria-current", btn.getAttribute("data-lang") === lang ? "true" : "false");
    });
    const summary = document.querySelector(".lang-switch summary span");
    if (summary) summary.textContent = lang.toUpperCase();
    try { localStorage.setItem(STORAGE, lang); } catch (e) { /* ignore */ }
    stampLinks(lang);
  }

  function stampLinks(lang) {
    document.querySelectorAll("a[href]").forEach(function (a) {
      const raw = a.getAttribute("href");
      if (!raw || /^(https?:|mailto:|tel:|#)/i.test(raw)) return;
      const hash = raw.includes("#") ? raw.slice(raw.indexOf("#")) : "";
      const base = raw.split("#")[0].split("?")[0];
      a.setAttribute("href", lang === "en" ? base + hash : base + "?lang=" + lang + hash);
    });
  }

  function setLang(lang) {
    if (!T[lang]) lang = "en";
    const url = new URL(window.location.href);
    if (lang === "en") url.searchParams.delete("lang");
    else url.searchParams.set("lang", lang);
    history.replaceState({}, "", url);
    apply(lang);
    const details = document.querySelector(".lang-switch");
    if (details) details.open = false;
  }

  function buildSwitcher() {
    const host = document.querySelector("[data-lang-switch]");
    if (!host) return;
    const details = document.createElement("details");
    details.className = "lang-switch";
    const summary = document.createElement("summary");
    summary.setAttribute("data-i18n-aria", "lang.aria");
    summary.innerHTML = '<span>EN</span>';
    const list = document.createElement("div");
    list.className = "lang-menu";
    list.setAttribute("role", "list");
    LANGS.forEach(function (item) {
      const btn = document.createElement("button");
      btn.type = "button";
      btn.setAttribute("data-lang", item.id);
      btn.setAttribute("role", "listitem");
      btn.textContent = item.label;
      btn.addEventListener("click", function () { setLang(item.id); });
      list.appendChild(btn);
    });
    details.appendChild(summary);
    details.appendChild(list);
    host.appendChild(details);
    document.addEventListener("click", function (e) {
      if (!details.contains(e.target)) details.open = false;
    });
  }

  buildSwitcher();
  apply(currentLang());
  window.thiniceSetLang = setLang;
